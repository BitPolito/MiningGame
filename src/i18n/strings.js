/** @param {Locale} locale */
/** @param {string} key */
/** @param {Record<string, string | number>} [vars] */
export function t(locale, key, vars) {
  let s = strings[locale]?.[key] ?? strings.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}
